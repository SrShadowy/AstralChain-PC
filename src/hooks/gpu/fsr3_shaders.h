/* [extra] AMD FSR 3.1 (Temporal Super Resolution + EASU + RCAS + Frame Generation)
 * GLSL 450 fragment shaders compiled at runtime via shaderc (shaders.c). */
#pragma once

/* Stage 1: Half-res 5-tap Cross Motion Estimation + Lucas-Kanade + Auto-Reactive & UI Mask.
 * Output RGBA8: RG = motion vector (zero-centered at 128/255), B = reactive, A = static UI mask. */
static const char fsr3_mv_frag_src[] =
    "#version 450\n"
    "layout(location=0) out vec4 o;\n"
    "layout(set=0, binding=0) uniform sampler2D t_curr;\n"
    "layout(set=0, binding=1) uniform sampler2D t_prev;\n"
    "layout(push_constant) uniform P { vec4 m; vec4 p; };\n"
    "float luma(vec3 c) { return c.g + 0.5 * (c.r + c.b); }\n"
    "void main() {\n"
    "  const float zc = 128.0 / 255.0;\n"
    "  if (p.z > 0.5) { o = vec4(zc, zc, 1.0, 0.0); return; }\n"
    "  vec2 texel = m.xy;\n"
    "  vec2 uv = gl_FragCoord.xy * texel;\n"
    "  vec3 c0 = texture(t_curr, uv).rgb;\n"
    "  vec3 p0 = texture(t_prev, uv).rgb;\n"
    "  float l_c = luma(c0), l_p0 = luma(p0);\n"
    "  float l_N = luma(texture(t_curr, uv + vec2(0.0, -texel.y)).rgb);\n"
    "  float l_S = luma(texture(t_curr, uv + vec2(0.0,  texel.y)).rgb);\n"
    "  float l_W = luma(texture(t_curr, uv + vec2(-texel.x, 0.0)).rgb);\n"
    "  float l_E = luma(texture(t_curr, uv + vec2( texel.x, 0.0)).rgb);\n"
    "  vec2 grad = vec2(l_E - l_W, l_S - l_N) * 0.5;\n"
    "  float edge = length(grad);\n"
    "  float raw_diff = length(c0 - p0);\n"
    "  float ui_mask = smoothstep(0.06, 0.20, edge) * (1.0 - smoothstep(0.005, 0.025, raw_diff));\n"
    "  vec2 best_off = vec2(0.0);\n"
    "  float best_sad = abs(l_c - l_p0) + 0.25 * raw_diff;\n"
    "  const vec2 offs[4] = vec2[4](vec2(-1,0), vec2(1,0), vec2(0,-1), vec2(0,1));\n"
    "  for (int i = 0; i < 4; i++) {\n"
    "    vec2 cand = offs[i] * texel;\n"
    "    vec3 pc = texture(t_prev, uv - cand).rgb;\n"
    "    float sad = abs(l_c - luma(pc)) + 0.25 * length(c0 - pc) + 0.003;\n"
    "    if (sad < best_sad) { best_sad = sad; best_off = cand; }\n"
    "  }\n"
    "  float it = l_c - (best_off == vec2(0.0) ? l_p0 : luma(texture(t_prev, uv - best_off).rgb));\n"
    "  vec2 lk = -it * grad / (dot(grad, grad) + 0.004);\n"
    "  vec2 mv = (best_off + clamp(lk, -1.25, 1.25) * texel) * (1.0 - ui_mask);\n"
    "  float reactive = clamp(best_sad * 2.8 + smoothstep(0.18, 0.50, abs(it)), 0.0, 1.0);\n"
    "  o = vec4(clamp(mv * 8.0 + zc, 0.0, 1.0), reactive, ui_mask);\n"
    "}\n";

/* Stage 2: Fused FSR 3.1 12-tap EASU Directional Reconstruction + Tangent Sub-Pixel Jitter
 * + In-Register RCAS Contrast-Adaptive Sharpening + YCoCg Variance-Clipped Temporal Accumulation.
 * Push constants: m = (in/out scale xy, offset zw), p = (in_w, in_h, phase (0=no jitter, >=50=spatial only), rcas). */
static const char fsr3_taa_frag_src[] =
    "#version 450\n"
    "layout(location=0) out vec4 o;\n"
    "layout(set=0, binding=0) uniform sampler2D t_curr;\n"
    "layout(set=0, binding=1) uniform sampler2D t_hist;\n"
    "layout(set=0, binding=2) uniform sampler2D t_mv;\n"
    "layout(push_constant) uniform P { vec4 m; vec4 p; };\n"
    "vec3 tap(ivec2 pos, ivec2 lim) { return texelFetch(t_curr, clamp(pos, ivec2(0), lim), 0).rgb; }\n"
    "float lum(vec3 c) { return c.g + 0.5 * (c.r + c.b); }\n"
    "vec3 rgb_to_ycocg(vec3 c) {\n"
    "  return vec3(0.25 * c.r + 0.5 * c.g + 0.25 * c.b, 0.5 * c.r - 0.5 * c.b, -0.25 * c.r + 0.5 * c.g - 0.25 * c.b);\n"
    "}\n"
    "vec3 ycocg_to_rgb(vec3 y) {\n"
    "  float tmp = y.x - y.z;\n"
    "  return clamp(vec3(tmp + y.y, y.x + y.z, tmp - y.y), 0.0, 1.0);\n"
    "}\n"
    "void setf(inout vec2 dir, inout float len, float w, float lA, float lB, float lC, float lD, float lE) {\n"
    "  float dx = lD - lB, dy = lE - lA;\n"
    "  float lx = clamp(abs(dx) / max(max(abs(lD - lC), abs(lC - lB)), 1.0 / 65536.0), 0.0, 1.0);\n"
    "  float ly = clamp(abs(dy) / max(max(abs(lE - lC), abs(lC - lA)), 1.0 / 65536.0), 0.0, 1.0);\n"
    "  dir += vec2(dx, dy) * w;\n"
    "  len += (lx * lx + ly * ly) * w;\n"
    "}\n"
    "void tapf(inout vec3 ac, inout float aw, vec2 off, vec2 dir, vec2 len2, float lob, float clp, vec3 c) {\n"
    "  vec2 v = vec2(dot(off, dir), dot(off, vec2(-dir.y, dir.x))) * len2;\n"
    "  float d2 = min(dot(v, v), clp);\n"
    "  float wb = 0.4 * d2 - 1.0, wa = lob * d2 - 1.0;\n"
    "  wb *= wb; wa *= wa;\n"
    "  float w = (1.5625 * wb - 0.5625) * wa;\n"
    "  ac += c * w; aw += w;\n"
    "}\n"
    "void main() {\n"
    "  const float zc = 128.0 / 255.0;\n"
    "  vec2 pp = floor(gl_FragCoord.xy) * m.xy + m.zw;\n"
    "  vec2 uv = (pp + 0.5) / p.xy;\n"
    "  vec4 mvd = (p.z < 50.0) ? texture(t_mv, uv) : vec4(zc, zc, 0.0, 0.0);\n"
    "  vec2 mv = (mvd.rg - zc) * 0.125;\n"
    "  float reactive = mvd.b, ui_mask = mvd.a;\n"
    "  vec2 fpf = floor(pp); pp -= fpf;\n"
    "  ivec2 fp = ivec2(fpf), lim = ivec2(p.xy) - 1;\n"
    "  vec3 bC = tap(fp + ivec2(0, -1), lim), cC = tap(fp + ivec2(1, -1), lim);\n"
    "  vec3 eC = tap(fp + ivec2(-1, 0), lim), fC = tap(fp, lim), gC = tap(fp + ivec2(1, 0), lim), hC = tap(fp + ivec2(2, 0), lim);\n"
    "  vec3 iC = tap(fp + ivec2(-1, 1), lim), jC = tap(fp + ivec2(0, 1), lim), kC = tap(fp + ivec2(1, 1), lim), lC = tap(fp + ivec2(2, 1), lim);\n"
    "  vec3 nC = tap(fp + ivec2(0, 2), lim), oC = tap(fp + ivec2(1, 2), lim);\n"
    "  float bL = lum(bC), cL = lum(cC), eL = lum(eC), fL = lum(fC), gL = lum(gC), hL = lum(hC);\n"
    "  float iL = lum(iC), jL = lum(jC), kL = lum(kC), lL = lum(lC), nL = lum(nC), oL = lum(oC);\n"
    "  vec2 dir = vec2(0.0); float len = 0.0;\n"
    "  setf(dir, len, (1.0 - pp.x) * (1.0 - pp.y), bL, eL, fL, gL, jL);\n"
    "  setf(dir, len, pp.x * (1.0 - pp.y), cL, fL, gL, hL, kL);\n"
    "  setf(dir, len, (1.0 - pp.x) * pp.y, fL, iL, jL, kL, nL);\n"
    "  setf(dir, len, pp.x * pp.y, gL, jL, kL, lL, oL);\n"
    "  float dr = dot(dir, dir);\n"
    "  dir = (dr < 1.0 / 32768.0) ? vec2(1.0, 0.0) : dir * inversesqrt(dr);\n"
    "  len *= 0.5; len *= len;\n"
    "  float stretch = dot(dir, dir) / max(abs(dir.x), abs(dir.y));\n"
    "  vec2 len2 = vec2(1.0 + (stretch - 1.0) * len, 1.0 - 0.5 * len);\n"
    "  float lob = 0.5 - 0.29 * len, clp = 1.0 / lob;\n"
    "  vec3 mn = min(min(fC, gC), min(jC, kC)), mx = max(max(fC, gC), max(jC, kC));\n"
    "  vec2 pp_j = pp;\n"
    "  if (p.z >= 0.5 && p.z < 50.0) {\n"
    "    vec2 j2 = fract(vec2(0.75487766, 0.56984029) * p.z) - 0.5;\n"
    "    vec2 tang = vec2(-dir.y, dir.x);\n"
    "    pp_j = clamp(pp + tang * dot(j2, tang) * 0.28 * len * (1.0 - ui_mask), vec2(0.0), vec2(1.0));\n"
    "  }\n"
    "  vec3 ac = vec3(0.0); float aw = 0.0;\n"
    "  tapf(ac, aw, vec2(0.0, -1.0) - pp_j, dir, len2, lob, clp, bC);\n"
    "  tapf(ac, aw, vec2(1.0, -1.0) - pp_j, dir, len2, lob, clp, cC);\n"
    "  tapf(ac, aw, vec2(-1.0, 1.0) - pp_j, dir, len2, lob, clp, iC);\n"
    "  tapf(ac, aw, vec2(0.0, 1.0) - pp_j, dir, len2, lob, clp, jC);\n"
    "  tapf(ac, aw, vec2(0.0, 0.0) - pp_j, dir, len2, lob, clp, fC);\n"
    "  tapf(ac, aw, vec2(-1.0, 0.0) - pp_j, dir, len2, lob, clp, eC);\n"
    "  tapf(ac, aw, vec2(1.0, 1.0) - pp_j, dir, len2, lob, clp, kC);\n"
    "  tapf(ac, aw, vec2(2.0, 1.0) - pp_j, dir, len2, lob, clp, lC);\n"
    "  tapf(ac, aw, vec2(2.0, 0.0) - pp_j, dir, len2, lob, clp, hC);\n"
    "  tapf(ac, aw, vec2(1.0, 0.0) - pp_j, dir, len2, lob, clp, gC);\n"
    "  tapf(ac, aw, vec2(1.0, 2.0) - pp_j, dir, len2, lob, clp, oC);\n"
    "  tapf(ac, aw, vec2(0.0, 2.0) - pp_j, dir, len2, lob, clp, nC);\n"
    "  vec3 curr = min(mx, max(mn, ac / max(aw, 1e-5)));\n"
    "  if (p.w > 0.001) {\n"
    "    float eL_c = lum(curr);\n"
    "    float nz = 0.25 * (fL + gL + jL + kL) - eL_c;\n"
    "    float rng = max(max(fL, gL), max(jL, kL)) - min(min(fL, gL), min(jL, kL));\n"
    "    nz = 1.0 - 0.5 * clamp(abs(nz) / max(rng, 1e-4), 0.0, 1.0);\n"
    "    vec3 hitMin = min(mn, curr) / (4.0 * mx + 1e-5);\n"
    "    vec3 hitMax = (1.0 - max(mx, curr)) / (4.0 * mn - 4.0 - 1e-5);\n"
    "    vec3 lobeRGB = max(-hitMin, hitMax);\n"
    "    float lobe = max(-0.1875, min(max(lobeRGB.r, max(lobeRGB.g, lobeRGB.b)), 0.0)) * p.w * nz;\n"
    "    curr = clamp((lobe * (fC + gC + jC + kC) + curr) / (4.0 * lobe + 1.0), 0.0, 1.0);\n"
    "  }\n"
    "  vec2 hist_uv = uv - mv;\n"
    "  bool oob = any(lessThan(hist_uv, vec2(0.0))) || any(greaterThan(hist_uv, vec2(1.0)));\n"
    "  if (p.z >= 50.0 || oob) { o = vec4(curr, 1.0); return; }\n"
    "  vec3 hist = texture(t_hist, hist_uv).rgb;\n"
    "  vec3 y0 = rgb_to_ycocg(fC), y1 = rgb_to_ycocg(gC), y2 = rgb_to_ycocg(jC), y3 = rgb_to_ycocg(kC);\n"
    "  vec3 yc = rgb_to_ycocg(curr), yb = rgb_to_ycocg(bC), ye = rgb_to_ycocg(eC);\n"
    "  vec3 mu = (y0 + y1 + y2 + y3 + yc + yb + ye) / 7.0;\n"
    "  vec3 m2 = (y0*y0 + y1*y1 + y2*y2 + y3*y3 + yc*yc + yb*yb + ye*ye) / 7.0;\n"
    "  vec3 sigma = sqrt(max(m2 - mu * mu, vec3(0.0)));\n"
    "  float gamma = mix(0.75, 0.30, clamp(reactive + ui_mask * 0.85, 0.0, 1.0));\n"
    "  hist = ycocg_to_rgb(clamp(rgb_to_ycocg(hist), mu - gamma * sigma, mu + gamma * sigma));\n"
    "  float mv_px = length(mv * p.xy);\n"
    "  float alpha = mix(0.55, 0.05, clamp(reactive * 0.90 + ui_mask * 0.95 + mv_px * 0.18, 0.0, 1.0));\n"
    "  o = vec4(mix(curr, hist, alpha), 1.0);\n"
    "}\n";

/* Stage 3: Standalone RCAS (used when FrameGen is active without FSR 3.1 Upscaler). */
static const char fsr3_rcas_frag_src[] =
    "#version 450\n"
    "layout(location=0) out vec4 o;\n"
    "layout(set=0, binding=0) uniform sampler2D t_in;\n"
    "layout(push_constant) uniform P { vec4 m; vec4 p; };\n"
    "void main() {\n"
    "  vec2 off = m.xy;\n"
    "  vec2 uv = gl_FragCoord.xy * off;\n"
    "  vec3 e = texture(t_in, uv).rgb;\n"
    "  if (p.x <= 0.001) { o = vec4(e, 1.0); return; }\n"
    "  vec3 b = texture(t_in, uv + vec2(0.0, -off.y)).rgb;\n"
    "  vec3 d = texture(t_in, uv + vec2(-off.x, 0.0)).rgb;\n"
    "  vec3 f = texture(t_in, uv + vec2( off.x, 0.0)).rgb;\n"
    "  vec3 h = texture(t_in, uv + vec2(0.0,  off.y)).rgb;\n"
    "  vec3 mn4 = min(min(b, d), min(f, h)), mx4 = max(max(b, d), max(f, h));\n"
    "  vec3 hitMin = min(mn4, e) / (4.0 * mx4 + 1e-5);\n"
    "  vec3 hitMax = (1.0 - max(mx4, e)) / (4.0 * mn4 - 4.0 - 1e-5);\n"
    "  vec3 lobeRGB = max(-hitMin, hitMax);\n"
    "  float lobe = max(-0.1875, min(max(lobeRGB.r, max(lobeRGB.g, lobeRGB.b)), 0.0)) * p.x;\n"
    "  o = vec4(clamp((lobe * (b + d + f + h) + e) / (4.0 * lobe + 1.0), 0.0, 1.0), 1.0);\n"
    "}\n";

/* Stage 4: FSR 3.1 Frame Generation (Optical-Flow Midpoint Interpolation U_{t-0.5} + HUD Guard). */
static const char fsr3_fg_frag_src[] =
    "#version 450\n"
    "layout(location=0) out vec4 o;\n"
    "layout(set=0, binding=0) uniform sampler2D t_curr;\n"
    "layout(set=0, binding=1) uniform sampler2D t_prev;\n"
    "layout(set=0, binding=2) uniform sampler2D t_mv;\n"
    "layout(push_constant) uniform P { vec4 m; vec4 p; };\n"
    "void main() {\n"
    "  vec2 uv = gl_FragCoord.xy * m.xy;\n"
    "  vec3 c_now = texture(t_curr, uv).rgb;\n"
    "  if (p.y > 0.5) { o = vec4(c_now, 1.0); return; }\n"
    "  const float zc = 128.0 / 255.0;\n"
    "  vec4 mvd = texture(t_mv, uv);\n"
    "  vec2 mv = (mvd.rg - zc) * 0.125;\n"
    "  float reactive = mvd.b, ui_mask = mvd.a;\n"
    "  vec3 f_warp = texture(t_prev, clamp(uv - 0.5 * mv, 0.0, 1.0)).rgb;\n"
    "  vec3 b_warp = texture(t_curr, clamp(uv + 0.5 * mv, 0.0, 1.0)).rgb;\n"
    "  float warp_err = length(f_warp - b_warp);\n"
    "  float cut = smoothstep(0.30, 0.60, warp_err + reactive * 0.45);\n"
    "  vec3 interp = mix(0.5 * (f_warp + b_warp), b_warp, smoothstep(0.08, 0.25, warp_err));\n"
    "  vec3 res = mix(interp, c_now, max(ui_mask, cut));\n"
    "  o = vec4(clamp(res, 0.0, 1.0), 1.0);\n"
    "}\n";
