static inline void extra_cut_fallback(int w, int h, uint8_t *c, const wchar_t *text, float bx0, float by0, float bx1, float by1) {
    int n = (int)wcslen(text);
    if (!n) return;
    float bw = bx1 - bx0, bh = by1 - by0;
    int scale = (int)fminf(bh / 8.0f, bw / (n * 8.0f));
    if (scale < 1) scale = 1;
    float total_w = n * 8.0f * scale;
    float total_h = 8.0f * scale;
    float sx = bx0 + (bw - total_w) / 2.0f;
    float sy = by0 + (bh - total_h) / 2.0f;

    for (int i = 0; i < n; i++) {
        wchar_t ch = text[i];
        if (ch < 32 || ch > 126) ch = '?';
        const uint8_t *glyph = s_font8x8_basic[ch - 32];
        for (int r = 0; r < 8; r++) {
            uint8_t row = glyph[r];
            for (int col = 0; col < 8; col++) {
                if (row & (1 << (7 - col))) {
                    int px0 = (int)(sx + (i * 8 + col) * scale);
                    int py0 = (int)(sy + r * scale);
                    for (int dy = 0; dy < scale; dy++) {
                        int py = py0 + dy;
                        if (py < 0 || py >= h) continue;
                        for (int dx = 0; dx < scale; dx++) {
                            int px = px0 + dx;
                            if (px < 0 || px >= w) continue;
                            c[py * w + px] = 0;
                        }
                    }
                }
            }
        }
    }
}

static inline void extra_cut_text(int w, int h, uint8_t *c, const wchar_t *text, float bx0, float by0, float bx1, float by1) {
    if (!text || !text[0]) return;
    if (!extra_font_init()) {
        extra_cut_fallback(w, h, c, text, bx0, by0, bx1, by1);
        return;
    }
    int n = (int)wcslen(text);
    float bw = bx1 - bx0, bh = by1 - by0;
    if (bw < 4 || bh < 4) return;

    int best_h = (int)(bh * 0.85f);
    for (; best_h >= 8; best_h = best_h * 9 / 10) {
        s_ft_set_sizes(s_ft_face, 0, best_h);
        int total_adv = 0;
        for (int i = 0; i < n; i++) {
            if (s_ft_load_char(s_ft_face, (unsigned long)text[i], 4) == 0) {
                void *glyph = ((void **)s_ft_face)[19];
                total_adv += (int)(*(long *)((char *)glyph + 128) >> 6);
            }
        }
        if (total_adv <= (int)bw) break;
    }

    s_ft_set_sizes(s_ft_face, 0, best_h);
    int total_adv = 0, max_top = -999, min_bot = 999;
    for (int i = 0; i < n; i++) {
        if (s_ft_load_char(s_ft_face, (unsigned long)text[i], 4) == 0) {
            void *glyph = ((void **)s_ft_face)[19];
            total_adv += (int)(*(long *)((char *)glyph + 128) >> 6);
            ExtraFT_Bitmap *bm = (ExtraFT_Bitmap *)((char *)glyph + 152);
            int bt = *(int *)((char *)glyph + 196);
            if (bm->rows > 0) {
                if (bt > max_top) max_top = bt;
                int bb = bt - (int)bm->rows;
                if (bb < min_bot) min_bot = bb;
            }
        }
    }
    if (max_top == -999) max_top = best_h;
    if (min_bot == 999) min_bot = 0;

    float cur_x = bx0 + (bw - total_adv) / 2.0f;
    float baseline_y = by0 + (bh + (max_top + min_bot)) / 2.0f;

    for (int i = 0; i < n; i++) {
        if (s_ft_load_char(s_ft_face, (unsigned long)text[i], 4) != 0) continue;
        void *glyph = ((void **)s_ft_face)[19];
        ExtraFT_Bitmap *bm = (ExtraFT_Bitmap *)((char *)glyph + 152);
        int bl = *(int *)((char *)glyph + 192), bt = *(int *)((char *)glyph + 196);
        long adv = *(long *)((char *)glyph + 128) >> 6;
        int gx0 = (int)roundf(cur_x + bl), gy0 = (int)roundf(baseline_y - bt);

        for (unsigned int r = 0; r < bm->rows; r++) {
            int py = gy0 + (int)r;
            if (py < 0 || py >= h) continue;
            for (unsigned int col = 0; col < bm->width; col++) {
                int px = gx0 + (int)col;
                if (px < 0 || px >= w) continue;
                if (bm->buffer[r * bm->pitch + col] > 64) c[py * w + px] = 0;
            }
        }
        cur_x += (float)adv;
    }
}
