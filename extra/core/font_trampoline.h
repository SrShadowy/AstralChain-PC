static void *s_ft_so = NULL;
static void *s_ft_lib = NULL;
static void *s_ft_face = NULL;
static int (*s_ft_init)(void **);
static int (*s_ft_new_face)(void *, const char *, long, void **);
static int (*s_ft_set_sizes)(void *, unsigned int, unsigned int);
static int (*s_ft_load_char)(void *, unsigned long, int);

static inline int extra_prompts_active(void) {
    const char *e = getenv("AC_PROMPTS");
    if (e && (!strcmp(e, "switch") || !strcmp(e, "0"))) return 0;
    if (e && (!strcmp(e, "keyboard") || !strcmp(e, "1"))) return 1;
    return extra_get_active_device();
}

static inline uint32_t extra_prompt_generation(void) {
    const char *e = getenv("AC_PROMPTS");
    if (e && (!strcmp(e, "switch") || !strcmp(e, "0") || !strcmp(e, "keyboard") || !strcmp(e, "1"))) return 1;
    return extra_get_prompt_generation();
}

static inline int extra_prompts_enabled(const char *e) {
    (void)e;
    return extra_prompts_active();
}

static inline bool extra_font_init(void) {
    if (s_ft_face) return true;
    if (!s_ft_so) {
        s_ft_so = dlopen("libfreetype.so.6", RTLD_NOW | RTLD_LOCAL);
        if (!s_ft_so) s_ft_so = dlopen("libfreetype.so", RTLD_NOW | RTLD_LOCAL);
        if (!s_ft_so) return false;
    }
    s_ft_init = (int (*)(void **))dlsym(s_ft_so, "FT_Init_FreeType");
    s_ft_new_face = (int (*)(void *, const char *, long, void **))dlsym(s_ft_so, "FT_New_Face");
    s_ft_set_sizes = (int (*)(void *, unsigned int, unsigned int))dlsym(s_ft_so, "FT_Set_Pixel_Sizes");
    s_ft_load_char = (int (*)(void *, unsigned long, int))dlsym(s_ft_so, "FT_Load_Char");
    if (!s_ft_init || !s_ft_new_face || !s_ft_set_sizes || !s_ft_load_char) return false;
    if (!s_ft_lib && s_ft_init(&s_ft_lib) != 0) return false;

    static const char *const fonts[] = {
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/TTF/DejaVuSans.ttf",
        "/usr/share/fonts/noto/NotoSans-Regular.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
    };
    for (size_t i = 0; i < sizeof(fonts) / sizeof(fonts[0]); i++) {
        if (s_ft_new_face(s_ft_lib, fonts[i], 0, &s_ft_face) == 0) {
            printf("[prompts] FreeType loaded font: %s\n", fonts[i]);
            return true;
        }
    }
    return false;
}

