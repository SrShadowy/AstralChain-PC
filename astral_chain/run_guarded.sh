#!/usr/bin/env bash
# Astral Chain PC: guarded game execution on Linux.
set -e
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT"

RUN_DIR="build/game"
SECONDS_LIMIT=604800
EXTRA_ENV=""
INPUT_SCRIPT=""
WRAPPER=""

while [ $# -gt 0 ]; do
    case "$1" in
        --run|-Run)
            RUN_DIR="$2"
            shift 2
            ;;
        --seconds|-Seconds)
            SECONDS_LIMIT="$2"
            shift 2
            ;;
        --script|-Script)
            INPUT_SCRIPT="$2"
            shift 2
            ;;
        --env|-Env)
            EXTRA_ENV="$2"
            shift 2
            ;;
        --wrapper|-Wrapper)
            WRAPPER="$2"
            shift 2
            ;;
        *)
            shift
            ;;
    esac
done

# Load run-env.txt generated by native_trace if available # [extra]
RUN_ENV_FILE="$RUN_DIR/run-env.txt" # [extra]
if [ ! -f "$RUN_ENV_FILE" ] && [ -f "$(dirname "$RUN_DIR")/game-old/run-env.txt" ]; then # [extra]
    RUN_ENV_FILE="$(dirname "$RUN_DIR")/game-old/run-env.txt" # [extra]
fi # [extra]
if [ -f "$RUN_ENV_FILE" ]; then
    while IFS='=' read -r key val || [ -n "$key" ]; do
        [[ "$key" =~ ^#.*$ ]] && continue
        [ -z "$key" ] && continue
        export "$key=$val"
    done < "$RUN_ENV_FILE"
fi

# Apply extra environment variables (format: KEY=VAL;KEY2=VAL2)
if [ -n "$EXTRA_ENV" ]; then
    IFS=';' read -ra VARS <<< "$EXTRA_ENV"
    for item in "${VARS[@]}"; do
        if [ -n "$item" ]; then
            export "$item"
        fi
    done
fi

export LARECOMP_VK_PRESENT="${LARECOMP_VK_PRESENT:-mailbox}"

if [ -n "$INPUT_SCRIPT" ]; then
    export AC_INPUT_SCRIPT="$INPUT_SCRIPT"
fi

if [ ! -d "$RUN_DIR" ]; then
    echo "Error: run directory $RUN_DIR does not exist." >&2
    exit 1
fi
RUN_DIR_ABS="$(cd "$RUN_DIR" && pwd)"
ROUND_DIR="$RUN_DIR_ABS/round-00"
EXE="$ROUND_DIR/trace"
RELOCATIONS="$ROUND_DIR/relocations.bin"

if [ ! -x "$EXE" ]; then
    echo "Error: game executable not found at $EXE. Run ./setup.sh or launcher first." >&2
    exit 1
fi

if [ -n "$WRAPPER" ]; then
    if [ "$SECONDS_LIMIT" -ge 86400 ]; then
        exec $WRAPPER "$EXE" "$RELOCATIONS"
    else
        exec timeout --foreground --kill-after=2s "$SECONDS_LIMIT" $WRAPPER "$EXE" "$RELOCATIONS"
    fi
else
    if [ "$SECONDS_LIMIT" -ge 86400 ]; then
        exec "$EXE" "$RELOCATIONS"
    else
        exec timeout --foreground --kill-after=2s "$SECONDS_LIMIT" "$EXE" "$RELOCATIONS"
    fi
fi
